#!/usr/bin/env python3
"""Create a Stage C world variant: sim/worlds/variants/<name>/sar_walls.sdf, the default world with only the target
pose changed (world name unchanged, so every topic stays the same). Refuses to overwrite, and refuses target positions
that fail the stand-in's validity rule (sar_standin_env.valid_random_target: clear of walls and of the start).

Usage: .venv/bin/python tools/make_world_variant.py <name> <x_ned> <y_ned>
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import sar_task  # noqa: E402

BASE_POSE = "<pose>3 -3 0.055 0 0 0</pose>"     # the default target pose (ENU), exactly once in the base world


def variant_text(base_text: str, name: str, x_ned: float, y_ned: float) -> str:
    target_start = base_text.index('<model name="target">')
    target_end = base_text.index("</model>", target_start)
    block = base_text[target_start:target_end]
    if base_text.count(BASE_POSE) != 1 or block.count(BASE_POSE) != 1:
        raise ValueError("base world target pose not found exactly once inside the target model")
    pose = f"<pose>{y_ned:g} {x_ned:g} 0.055 0 0 0</pose>"         # NED -> ENU: x_enu = y_ned, y_enu = x_ned
    header = (f"<!-- Stage C world variant {name!r}: generated by tools/make_world_variant.py from sar_walls.sdf; "
              f"only the target pose differs (PX4 NED x={x_ned:g}, y={y_ned:g}). -->\n")
    text = base_text[:target_start] + block.replace(BASE_POSE, pose) + base_text[target_end:]
    first_newline = text.index("\n") + 1                               # keep the XML declaration first
    return text[:first_newline] + header + text[first_newline:]


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("name")
    p.add_argument("x_ned", type=float)
    p.add_argument("y_ned", type=float)
    args = p.parse_args(argv)
    if not sar_task._VARIANT_NAME.fullmatch(args.name):
        p.error(f"malformed variant name {args.name!r}")
    from sar_standin_env import SarStandInEnv, valid_random_target
    if not valid_random_target(args.x_ned, args.y_ned, SarStandInEnv().walls):
        p.error(f"target NED ({args.x_ned}, {args.y_ned}) fails the stand-in validity rule")
    out = sar_task.WORLD_VARIANTS / args.name / sar_task.WORLD_SDF.name
    out.parent.mkdir(parents=True, exist_ok=False)
    out.write_text(variant_text(sar_task.WORLD_SDF.read_text(), args.name, args.x_ned, args.y_ned))
    target = sar_task.load_target(out)
    print(f"{out}: target NED ({target.x_ned}, {target.y_ned}), sha256 {sar_task.file_sha256(out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
